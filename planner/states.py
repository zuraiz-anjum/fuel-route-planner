_BY_NAME = {name.casefold(): code for code, name in STATE_NAMES.items()}


def state_code(text):
    """"TX", "tx" or "Texas" as "TX"; None for anything that is not a state."""
    text = " ".join(text.split())
    if len(text) == 2 and text.upper() in STATE_NAMES:
        return text.upper()
    return _BY_NAME.get(text.casefold())
